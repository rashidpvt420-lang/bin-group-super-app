#!/usr/bin/env node
/**
 * Postdeploy release gate.
 *
 * Runs after `deploy-firebase-production-stack` has actually deployed this
 * commit to production, and gates whether the release may be marked public
 * (or reach the artifact-upload step at all). Unlike the predeploy gate,
 * every check here targets LIVE production — this is where business E2E,
 * launch audit, SMTP, and App Check are actually exercised against the
 * commit that is now serving real traffic.
 *
 * Fail-closed throughout: a missing file, a script that can't run, or a
 * malformed report is a failure, never a silent pass.
 *
 * Check functions are exported (pure, take root/env/data as parameters) so
 * the file-based logic can be unit-tested with fixtures. The functions that
 * spawn real E2E/SMTP/route checks are integration-level by nature and are
 * exercised by actually running this gate in the deploy workflow.
 */
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import {
  validateDeploymentDocument,
  evaluatePilotEligibility,
  evidencePath,
  deploymentEvidencePath,
  readJsonSafe,
  PRODUCTION,
} from './lib/launch-honesty.mjs';
import {
  requireFullCommitSha,
  checkProductionIncidentsFailClosed,
  scanArtifactsForAppCheckFailures,
  printResult,
} from './lib/launch-approval-shared.mjs';

const npmCmd = process.platform === 'win32' ? 'npm.cmd' : 'npm';

export function checkCommitAndDigestInputs(env) {
  const failures = [];
  const shaCheck = requireFullCommitSha(env.GITHUB_SHA, 'GITHUB_SHA');
  if (!shaCheck.ok) failures.push(shaCheck.error);

  const digest = String(env.VALIDATED_ARTIFACT_DIGEST || '').trim();
  if (!digest || digest.length < 32) {
    failures.push('VALIDATED_ARTIFACT_DIGEST is missing or too short.');
  }
  return { failures, commitSha: shaCheck.ok ? shaCheck.sha : null, digest: digest || null };
}

export function checkDeploymentDocument(root, commitSha, artifactDigest) {
  const failures = [];
  const doc = readJsonSafe(deploymentEvidencePath(root), null);
  if (!doc) {
    return ['launch_package/production-deployment.json is missing. Deployment metadata must be generated by the workflow before this gate can run.'];
  }
  failures.push(...validateDeploymentDocument(doc, commitSha, { root, requireWorkflowProvenance: true }));

  if (artifactDigest && doc.artifactDigest !== artifactDigest) {
    failures.push(`Deployed artifact digest (${doc.artifactDigest || 'missing'}) does not match VALIDATED_ARTIFACT_DIGEST (${artifactDigest}).`);
  }
  return failures;
}

/** Pure evaluation of already-collected evidence — no spawning. Unit-testable with fixtures. */
export function evaluateCollectedEvidence(root, commitSha) {
  const failures = [];
  const evidenceBatch = readJsonSafe(evidencePath(root), { records: [] });
  const deploymentDoc = readJsonSafe(deploymentEvidencePath(root), null);
  const pilot = evaluatePilotEligibility({ evidenceBatch, commitSha, deploymentDoc, root });
  if (!pilot.pilotEligible) {
    if (pilot.missing.length) failures.push(`Missing required evidence: ${pilot.missing.join(', ')}`);
    if (pilot.invalid.length) failures.push(...pilot.invalid.map((m) => `Invalid evidence: ${m}`));
  }

  const appCheckHits = scanArtifactsForAppCheckFailures(root);
  if (appCheckHits.length) {
    failures.push(`App Check token-fetch failures found in: ${appCheckHits.join(', ')}. This means requests were rejected at the App Check layer, not merely denied by security rules.`);
  }
  return failures;
}

export function checkLiveBilling(root, env) {
  if (env.LAUNCH_BANK_ONLY === '1') {
    return { failures: [], note: 'LAUNCH_BANK_ONLY=1 — live_billing (Stripe) is deferred for the controlled bank-transfer pilot, not required.' };
  }
  const readiness = readJsonSafe(path.join(root, 'launch_package/hard-launch-readiness.json'), null);
  if (!readiness) {
    return { failures: ['launch_package/hard-launch-readiness.json is missing. Cannot verify live_billing attestation for public launch.'], note: null };
  }
  const gate = (readiness.hardLaunchGates || []).find((g) => g.id === 'live_billing');
  const positiveStatuses = new Set(['passed', 'attested', 'verified']);
  if (!gate || !positiveStatuses.has(String(gate.status || ''))) {
    return {
      failures: [`live_billing gate is not attested (status: ${gate?.status || 'missing'}). Public launch requires real sk_live_/whsec_ Stripe secrets and a completed live AED checkout + webhook proof — see hard_launch runbook.`],
      note: null,
    };
  }
  return { failures: [], note: null };
}

export function checkPilotCompletion(root) {
  const readiness = readJsonSafe(path.join(root, 'launch_package/hard-launch-readiness.json'), null);
  if (!readiness) {
    return { failures: ['launch_package/hard-launch-readiness.json is missing. Cannot verify pilot_no_p0_p1 attestation.'], note: null };
  }
  const gate = (readiness.hardLaunchGates || []).find((g) => g.id === 'pilot_no_p0_p1');
  const positiveStatuses = new Set(['passed', 'attested', 'verified']);
  if (!gate || !positiveStatuses.has(String(gate.status || ''))) {
    return {
      failures: [],
      note: `pilot_no_p0_p1 is not yet attested (status: ${gate?.status || 'missing'}). This is expected for a first controlled-pilot deploy and does not block the pilot itself — it blocks marking the release PUBLIC_LAUNCH_READY.`,
    };
  }
  return { failures: [], note: null };
}

function run(label, command, args, extraEnv = {}) {
  console.log(`\n→ ${label}: ${command} ${args.join(' ')}`);
  // Windows requires shell:true to resolve .cmd shims (npm.cmd); Linux CI runners don't need it.
  const result = spawnSync(command, args, {
    cwd: process.cwd(),
    stdio: 'inherit',
    env: { ...process.env, ...extraEnv },
    shell: process.platform === 'win32',
  });
  const ok = (result.status ?? 1) === 0;
  return { ok, failure: ok ? null : `${label} failed (exit ${result.status ?? 'spawn error'}).` };
}

function main() {
  console.log('\n=== Postdeploy Release Gate ===\n');
  const root = process.cwd();
  const env = process.env;
  const failures = [];

  const { failures: inputFailures, commitSha, digest } = checkCommitAndDigestInputs(env);
  failures.push(...inputFailures);
  failures.push(...checkDeploymentDocument(root, commitSha, digest));
  failures.push(...checkProductionIncidentsFailClosed(root));

  const routeCheck = run('Production route check', npmCmd, ['run', 'test:e2e:gate11:routes'], {
    E2E_BASE_URL: PRODUCTION.mainUrl,
    E2E_ADMIN_BASE_URL: PRODUCTION.adminUrl,
  });
  if (!routeCheck.ok) failures.push(routeCheck.failure);

  const appCheckReady = run('App Check debug-token readiness', npmCmd, ['run', 'e2e:ensure-appcheck']);
  if (!appCheckReady.ok) failures.push(appCheckReady.failure);

  const smtp = run('SMTP live delivery', process.execPath, ['scripts/test-trigger-email.mjs']);
  if (!smtp.ok) failures.push(smtp.failure);

  if (commitSha) {
    const evidence = run(
      'Business E2E + launch audit + deployment evidence (all-required)',
      npmCmd,
      ['run', 'launch:evidence:run', '--', '--suite', 'all-required'],
      { E2E_BASE_URL: PRODUCTION.mainUrl, E2E_ADMIN_BASE_URL: PRODUCTION.adminUrl },
    );
    if (!evidence.ok) failures.push(evidence.failure);
    failures.push(...evaluateCollectedEvidence(root, commitSha));
  }

  const billing = checkLiveBilling(root, env);
  failures.push(...billing.failures);
  if (billing.note) console.log(`\n${billing.note}`);

  const pilot = checkPilotCompletion(root);
  failures.push(...pilot.failures);
  if (pilot.note) console.log(`\n${pilot.note}`);

  const passed = printResult('Postdeploy release gate', failures);
  process.exit(passed ? 0 : 1);
}

if (path.basename(process.argv[1] || '') === 'postdeploy-release-gate.mjs') {
  main();
}

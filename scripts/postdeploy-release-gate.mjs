#!/usr/bin/env node
/**
 * Post-deployment release gate (fail-closed).
 *
 * Runs AFTER production deploy + verify:production-deployment.
 * May set publicReleaseCleared only when every live proof passes.
 * HARD_LAUNCH_CLAIM remains false — this gate never flips that constant.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import {
  DEPLOYMENT_MAX_AGE_MS,
  DEPLOYMENT_META_PATH,
  EVIDENCE_BATCH_PATH,
  PREDEPLOY_APPROVAL_PATH,
  PUBLIC_RELEASE_STATUS_PATH,
  checkProductionIncidents,
  requireArtifactDigest,
  requireFullSha,
  requireGitHubProductionEnvironment,
  validateRecentTimestamp,
} from './lib/launch-gate-common.mjs';
import {
  HARD_LAUNCH_CLAIM,
  PRODUCTION,
  REQUIRED_PILOT_EVIDENCE,
  evaluatePilotEligibility,
  validateDeploymentDocument,
  validateEvidenceRecord,
} from './lib/launch-honesty.mjs';

const REQUIRED_POSTDEPLOY_EVIDENCE = Object.freeze([
  ...REQUIRED_PILOT_EVIDENCE,
]);

const APP_CHECK_FAILURE_RE =
  /app check|firebase.?app.?check|appcheck|permission-denied|insufficient permissions|status.?code.?(401|403|429)|\b403\b|\b429\b/i;

export function runPostdeployReleaseGate({
  root = process.cwd(),
  env = process.env,
  now = Date.now(),
  writeStatus = false,
} = {}) {
  const failures = [];

  requireGitHubProductionEnvironment(failures, env);
  const githubSha = requireFullSha(env.GITHUB_SHA, 'GITHUB_SHA', failures);
  const validatedDigest = requireArtifactDigest(
    env.VALIDATED_ARTIFACT_DIGEST,
    'VALIDATED_ARTIFACT_DIGEST',
    failures,
  );

  checkProductionIncidents(failures, { root, now, env });

  const approvalPath = path.join(root, PREDEPLOY_APPROVAL_PATH);
  let releaseId = String(env.RELEASE_ID || '').trim();
  if (!existsSync(approvalPath)) {
    failures.push(
      `${PREDEPLOY_APPROVAL_PATH} missing. Postdeploy release clearance must bind to the predeploy releaseId.`,
    );
  } else {
    try {
      const approval = JSON.parse(readFileSync(approvalPath, 'utf8'));
      const boundReleaseId = String(approval.releaseId || '').trim();
      if (!boundReleaseId) {
        failures.push('predeploy-approval.json missing releaseId binding.');
      } else {
        releaseId = boundReleaseId;
        if (env.RELEASE_ID && String(env.RELEASE_ID).trim() !== boundReleaseId) {
          failures.push(
            `RELEASE_ID (${env.RELEASE_ID}) does not match predeploy approval releaseId (${boundReleaseId}).`,
          );
        }
        if (githubSha && String(approval.commitSha || '').trim() !== githubSha) {
          failures.push('predeploy approval commitSha does not equal GITHUB_SHA.');
        }
      }
    } catch (err) {
      failures.push(`predeploy-approval.json malformed: ${err.message}`);
    }
  }

  const deployPath = path.join(root, DEPLOYMENT_META_PATH);
  let deploymentDoc = null;
  if (!existsSync(deployPath)) {
    failures.push(
      'production-deployment.json missing. Postdeploy requires workflow-generated deployment metadata.',
    );
  } else {
    try {
      deploymentDoc = JSON.parse(readFileSync(deployPath, 'utf8'));
    } catch (err) {
      failures.push(`production-deployment.json malformed: ${err.message}`);
    }
    if (deploymentDoc) {
      if (String(deploymentDoc.source || '') !== 'firebase-production-deploy-workflow') {
        failures.push(
          'production-deployment.json must be generated by the production deploy workflow (source mismatch).',
        );
      }
      if (githubSha) {
        const metaErrors = validateDeploymentDocument(deploymentDoc, githubSha, {
          root,
          requireWorkflowProvenance: true,
        });
        for (const err of metaErrors) failures.push(`deployment: ${err}`);
      }
      if (githubSha && deploymentDoc.deployedCommitSha !== githubSha) {
        failures.push(
          `deployedCommitSha ${deploymentDoc.deployedCommitSha} != GITHUB_SHA ${githubSha}`,
        );
      }
      validateRecentTimestamp(
        deploymentDoc.deployedAt,
        DEPLOYMENT_MAX_AGE_MS,
        'deployment.deployedAt',
        failures,
      );
      validateRecentTimestamp(
        deploymentDoc.verifiedAt,
        DEPLOYMENT_MAX_AGE_MS,
        'deployment.verifiedAt',
        failures,
      );

      const deployedDigest = String(
        deploymentDoc.artifactDigest || deploymentDoc.validatedArtifactDigest || '',
      )
        .trim()
        .toLowerCase();
      if (!deployedDigest) {
        failures.push('deployment metadata missing artifactDigest / validatedArtifactDigest.');
      } else if (validatedDigest && deployedDigest !== validatedDigest) {
        failures.push('deployed artifact digest does not equal VALIDATED_ARTIFACT_DIGEST.');
      }
    }
  }

  const evidencePath = path.join(root, EVIDENCE_BATCH_PATH);
  let evidenceBatch = { records: [] };
  if (!existsSync(evidencePath)) {
    failures.push('launch-evidence-batch.json missing — live role/App Check/audit evidence required.');
  } else {
    try {
      evidenceBatch = JSON.parse(readFileSync(evidencePath, 'utf8'));
    } catch (err) {
      failures.push(`launch-evidence-batch.json malformed: ${err.message}`);
    }
  }

  const eligibility = evaluatePilotEligibility({
    evidenceBatch,
    commitSha: githubSha || 'missing',
    deploymentDoc,
    now,
    root,
  });

  if (!eligibility.pilotEligible) {
    for (const key of eligibility.missing || []) failures.push(`missing live evidence: ${key}`);
    for (const inv of eligibility.invalid || []) failures.push(`invalid evidence: ${inv}`);
  }

  if (githubSha) {
    for (const key of REQUIRED_POSTDEPLOY_EVIDENCE) {
      const record = (evidenceBatch.records || []).find(
        (r) => r.testName === key && r.commitSha === githubSha,
      );
      if (!record) {
        failures.push(`required postdeploy evidence missing for ${key}`);
        continue;
      }
      const check = validateEvidenceRecord(record, {
        commitSha: githubSha,
        now,
        root,
        revalidateArtifact: true,
      });
      if (!check.ok) failures.push(`${key}: ${check.reason}`);
      if (Number(record.failed || 0) > 0) failures.push(`${key}: failed count > 0`);
      if (Number(record.skipped || 0) > 0) failures.push(`${key}: skipped count > 0`);
    }
  }

  const gate11 = (evidenceBatch.records || []).find(
    (r) => r.testName === 'gate11ProductionSmoke' && r.commitSha === githubSha,
  );
  if (!gate11) {
    failures.push('Gate 11 authenticated production smoke evidence (gate11ProductionSmoke) is missing.');
  } else if (Number(gate11.passed || 0) < 12 || Number(gate11.failed || 0) > 0) {
    failures.push(`Gate 11 smoke must be 12/12 (passed=${gate11.passed} failed=${gate11.failed}).`);
  }

  const businessAggregate = (evidenceBatch.records || []).find(
    (r) => r.testName === 'businessWorkflows' && r.commitSha === githubSha,
  );
  if (!businessAggregate) {
    failures.push(
      'Business workflows 9/9 proof missing. Record testName=businessWorkflows with passed=9 failed=0 for this commit.',
    );
  } else if (Number(businessAggregate.passed || 0) < 9 || Number(businessAggregate.failed || 0) > 0) {
    failures.push(
      `Business workflows must be 9/9 (passed=${businessAggregate.passed} failed=${businessAggregate.failed}).`,
    );
  }

  for (const record of evidenceBatch.records || []) {
    if (record.commitSha !== githubSha) continue;
    const blob = `${record.proof || ''} ${record.notes || ''} ${JSON.stringify(record.appCheck || {})}`;
    if (APP_CHECK_FAILURE_RE.test(blob) && record.appCheckClean !== true) {
      failures.push(`App Check/permission contamination in evidence ${record.testName}.`);
    }
    if (record.appCheckFailures && Number(record.appCheckFailures) > 0) {
      failures.push(`App Check failures recorded for ${record.testName}: ${record.appCheckFailures}`);
    }
  }

  for (const item of [
    { envKey: 'POSTDEPLOY_ROUTES_OK', label: 'production routes verification' },
    { envKey: 'POSTDEPLOY_SMTP_OK', label: 'SMTP live delivery proof' },
    { envKey: 'POSTDEPLOY_APPCHECK_OK', label: 'App Check enforcement proof' },
    { envKey: 'POSTDEPLOY_SMOKE_OK', label: 'Gate 11 authenticated production smoke' },
    { envKey: 'POSTDEPLOY_BUSINESS_OK', label: 'business workflows 9/9 proof' },
    { envKey: 'POSTDEPLOY_AUDIT_OK', label: 'launch audit live evidence' },
  ]) {
    if (String(env[item.envKey] || '') !== 'true') {
      failures.push(`Missing ${item.label} marker (${item.envKey}=true).`);
    }
  }

  const launchMode = String(env.LAUNCH_MODE || '').trim();
  if (launchMode === 'public') {
    if (String(env.POSTDEPLOY_STRIPE_LIVE_OK || '') !== 'true') {
      failures.push(
        'Public launch requires POSTDEPLOY_STRIPE_LIVE_OK=true (live payment + webhook proof).',
      );
    }
  }

  const pilotNoP0 = (evidenceBatch.records || []).find(
    (r) => r.testName === 'pilot_no_p0_p1' && r.commitSha === githubSha,
  );
  if (!pilotNoP0 || pilotNoP0.exitCode !== 0) {
    failures.push('Completed pilot_no_p0_p1 evidence is required before public release clearance.');
  }

  const uniqueFailures = [...new Set(failures)];
  const ok = uniqueFailures.length === 0;
  const status = {
    status: ok ? 'passed' : 'failed',
    stage: 'postdeploy',
    commitSha: githubSha || null,
    releaseId: releaseId || null,
    validatedArtifactDigest: validatedDigest || null,
    publicReleaseCleared: ok,
    hardLaunchClaim: HARD_LAUNCH_CLAIM,
    pilotEligible: eligibility.pilotEligible === true,
    projectId: PRODUCTION.projectId,
    evaluatedAt: new Date(now).toISOString(),
    failures: uniqueFailures,
  };

  if (writeStatus) {
    mkdirSync(path.dirname(path.join(root, PUBLIC_RELEASE_STATUS_PATH)), { recursive: true });
    writeFileSync(path.join(root, PUBLIC_RELEASE_STATUS_PATH), `${JSON.stringify(status, null, 2)}\n`);
  }

  return { ok, failures: uniqueFailures, hardLaunchClaim: HARD_LAUNCH_CLAIM, status };
}

const isDirectRun =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname);

if (isDirectRun) {
  console.log('\n=== Post-deployment release gate ===\n');
  console.log(`hardLaunchClaim=${HARD_LAUNCH_CLAIM} (constant remains false)`);
  const result = runPostdeployReleaseGate({ writeStatus: true });
  if (result.ok) {
    console.log('PASS — postdeploy release checks succeeded.');
    console.log(`publicReleaseCleared=true hardLaunchClaim=${HARD_LAUNCH_CLAIM}`);
    process.exit(0);
  }
  console.error('FAIL — public release is NOT cleared:\n');
  for (const failure of result.failures) console.error(`- ${failure}`);
  console.error(`\npublicReleaseCleared=false hardLaunchClaim=${HARD_LAUNCH_CLAIM}`);
  process.exit(1);
}

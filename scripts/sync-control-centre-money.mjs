#!/usr/bin/env node
// Generates functions/shared/controlCentreMoney.js (CommonJS) from the reviewed Admin money modules so
// the scheduled control-centre summary uses exactly the same ledger maths as the Admin panel.
// Run: node scripts/sync-control-centre-money.mjs   Check: node scripts/sync-control-centre-money.mjs --check
import { readFileSync, writeFileSync } from 'node:fs';

const strip = (source) => source
  .replace(/^import .*$/gm, '')
  .replace(/^export (const|function) /gm, '$1 ');
const ledger = strip(readFileSync('apps/admin-panel/src/lib/canonicalPaymentLedger.mjs', 'utf8'));
const money = strip(readFileSync('apps/admin-panel/src/lib/controlCentreMoney.mjs', 'utf8'));
const output = `/* eslint-disable */
// GENERATED by scripts/sync-control-centre-money.mjs from apps/admin-panel/src/lib. Do not edit.
"use strict";
const ledgerModule = (() => {
${ledger}
return { summarizeCanonicalPaymentLedger, formatAedLedgerMoney };
})();
const moneyModule = (() => {
const { summarizeCanonicalPaymentLedger } = ledgerModule;
${money}
return { summarizeControlCentreMoney };
})();
module.exports = { ...ledgerModule, ...moneyModule };
`.replace(/\r\n?/g, '\n');
const target = 'functions/shared/controlCentreMoney.js';
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) { console.error(`${target} is stale; run node scripts/sync-control-centre-money.mjs`); process.exit(1); }
} else {
  writeFileSync(target, output, 'utf8');
}

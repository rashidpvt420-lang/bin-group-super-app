#!/usr/bin/env node
/**
 * Materialize non-secret Firebase Functions params for non-interactive deploy.
 *
 * The Firebase CLI still prompts when a defineInt default of 0 is the only
 * value, which breaks `firebase deploy --non-interactive`. Real dotenv files
 * must stay untracked; this writes the gitignored production project file from
 * the committed .example. Secrets are never written here.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

export const PRODUCTION_PROJECT_ID = 'bin-group-57c60';
export const FUNCTIONS_DIR = 'functions';
export const PARAM_EXAMPLE_FILE = path.join(FUNCTIONS_DIR, `.env.${PRODUCTION_PROJECT_ID}.example`);
export const PARAM_DOTENV_FILE = path.join(FUNCTIONS_DIR, `.env.${PRODUCTION_PROJECT_ID}`);
export const REQUIRED_PARAM_VALUES = Object.freeze({
  CRITICAL_FN_MIN_INSTANCES: '0',
});

const PARAM_RE = /\bdefine(?:Int|String|Boolean)\(\s*['"]([A-Z][A-Z0-9_]+)['"]/g;

function collectSourceFiles(dir, files = []) {
  if (!existsSync(dir)) return files;
  for (const entry of readdirSync(dir)) {
    if (entry === 'node_modules' || entry === 'lib' || entry === 'dist' || entry.startsWith('.')) continue;
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) {
      collectSourceFiles(full, files);
      continue;
    }
    if (/\.(ts|js|mjs|cjs)$/.test(entry)) files.push(full);
  }
  return files;
}

export function parseDotenv(source) {
  const values = {};
  for (const rawLine of String(source || '').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const cut = line.indexOf('=');
    if (cut <= 0) continue;
    const key = line.slice(0, cut).trim();
    let value = line.slice(cut + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values[key] = value;
  }
  return values;
}

export function definedDeployParams(functionsDir = FUNCTIONS_DIR) {
  const params = new Set();
  for (const file of collectSourceFiles(functionsDir)) {
    const source = readFileSync(file, 'utf8');
    PARAM_RE.lastIndex = 0;
    let match;
    while ((match = PARAM_RE.exec(source))) params.add(match[1]);
  }
  return params;
}

export function resolveFunctionsDeployParams({
  functionsDir = FUNCTIONS_DIR,
  examplePath = PARAM_EXAMPLE_FILE,
  requiredValues = REQUIRED_PARAM_VALUES,
} = {}) {
  if (!existsSync(examplePath)) {
    throw new Error(`Missing Functions param example: ${examplePath}`);
  }
  const values = parseDotenv(readFileSync(examplePath, 'utf8'));
  const declared = definedDeployParams(functionsDir);
  const missing = [...declared].filter((name) => !String(values[name] ?? '').length);
  if (missing.length) {
    throw new Error(
      `Functions param example is missing non-interactive values for: ${missing.join(', ')}`,
    );
  }
  for (const [name, expected] of Object.entries(requiredValues)) {
    if (values[name] !== expected) {
      throw new Error(`${name} must stay ${expected} (found ${values[name] ?? '<missing>'})`);
    }
  }
  return values;
}

export function serializeDotenv(values) {
  const lines = [
    '# Generated by scripts/write-functions-deploy-params.mjs for non-interactive firebase deploy.',
    '# Do not commit this file. Non-secret params only.',
  ];
  for (const name of Object.keys(values).sort()) {
    lines.push(`${name}=${values[name]}`);
  }
  return `${lines.join('\n')}\n`;
}

export function writeFunctionsDeployParams({
  projectId = PRODUCTION_PROJECT_ID,
  functionsDir = FUNCTIONS_DIR,
  examplePath = PARAM_EXAMPLE_FILE,
  targetPath = PARAM_DOTENV_FILE,
} = {}) {
  if (projectId !== PRODUCTION_PROJECT_ID) {
    throw new Error(`Refusing to write Functions params for unexpected project ${projectId}`);
  }
  const values = resolveFunctionsDeployParams({ functionsDir, examplePath });
  writeFileSync(targetPath, serializeDotenv(values), { mode: 0o600 });
  return { targetPath, values };
}

const isDirectRun = Boolean(process.argv[1]) && import.meta.url === pathToFileURL(process.argv[1]).href;

if (isDirectRun) {
  const result = writeFunctionsDeployParams({
    projectId: String(process.env.GCP_PROJECT_ID || PRODUCTION_PROJECT_ID).trim(),
  });
  console.log(`[functions-deploy-params] wrote ${result.targetPath}`);
}

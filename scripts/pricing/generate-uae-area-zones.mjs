// Generates the three identical uaeAreaZones2026.ts copies from the approved seed CSV
// (Founder approval 2026-10-14). Run: node scripts/pricing/generate-uae-area-zones.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const CSV = 'scripts/pricing/uae-area-zones-2026-10-14.csv';
const TARGETS = ['functions/pricing/uaeAreaZones2026.ts', 'src/utils/uaeAreaZones2026.ts', 'packages/shared/src/pricing/uaeAreaZones2026.ts'];

function parseCsv(text) {
  const rows = []; let row = []; let cell = ''; let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) { if (ch === '"' && text[i + 1] === '"') { cell += '"'; i += 1; } else if (ch === '"') quoted = false; else cell += ch; }
    else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(cell); cell = ''; }
    else if (ch === '\n' || ch === '\r') { if (ch === '\r' && text[i + 1] === '\n') i += 1; row.push(cell); rows.push(row); row = []; cell = ''; }
    else cell += ch;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows.filter((r) => r.length > 1);
}

function region(emirate) {
  if (emirate.includes('(Al Ain)')) return 'Al Ain';
  if (emirate.includes('(Al Dhafra)')) return 'Al Dhafra';
  return emirate;
}

const [header, ...body] = parseCsv(readFileSync(CSV, 'utf8'));
const idx = Object.fromEntries(header.map((h, i) => [h, i]));
const entries = body.map((r) => {
  const area = r[idx.area];
  const names = area.split(' / ').map((s) => s.replace(/\(.*?\)/g, '').trim()).filter(Boolean);
  const paren = [...area.matchAll(/\(([^)]+)\)/g)].map((m) => m[1].trim());
  const aliases = Array.from(new Set([area, ...names, ...paren, ...r[idx.aliases_arabic].split('|').map((s) => s.trim())].filter(Boolean)));
  return { region: region(r[idx.emirate]), area, zone: r[idx.zone], segment: r[idx.segment], confidence: r[idx.confidence], aliases };
});

const out = `// GENERATED by scripts/pricing/generate-uae-area-zones.mjs from ${CSV}. Do not edit by hand.
// Founder-approved area -> zone map (2026-10-14). Zones are ranked within each emirate from cited
// rent / sale price per sqft data; see the CSV for metrics and source URLs.
export interface UaeAreaZoneEntry {
  region: string;
  area: string;
  zone: 'A' | 'B' | 'C';
  segment: string;
  confidence: string;
  aliases: string[];
}

export const UAE_AREA_ZONES_2026: ReadonlyArray<UaeAreaZoneEntry> = ${JSON.stringify(entries, null, 2)};
`;
for (const t of TARGETS) writeFileSync(t, out);
console.log(`wrote ${entries.length} areas to ${TARGETS.length} copies`);

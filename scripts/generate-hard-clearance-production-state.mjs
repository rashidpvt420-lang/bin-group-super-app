#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  deploymentEvidencePath,
  gitSha,
} from './lib/launch-honesty.mjs';
import { runProductionOtpMailboxPreflight } from './lib/production-otp-mailbox-preflight.mjs';
import {
  HARD_CLEARANCE_PRODUCTION_STATE_RELATIVE_PATH,
  buildHardClearanceProductionState,
  sha256Text,
  validateHardClearanceProductionState,
} from './lib/hard-clearance-production-state.mjs';
import { verifyFirebasePhoneAuthProduction } from './verify-firebase-phone-auth-production.mjs';
import { verifyAdminMfaProduction } from './verify-admin-mfa-production.mjs';

const EXPECTED_PROJECT_ID = 'bin-group-57c60';
const EXPECTED_WORKFLOW = 'Live Role Smoke Tests';
const EXPECTED_JOB = 'hard-clearance-production-state';

const text = (value) => String(value ?? '').trim();

function parseJson(raw, label) {
  try {
    return JSON.parse(raw);
  } catch {
    throw new Error(`${label} is missing or malformed.`);
  }
}

function assertProtectedContext({ env, currentCommitSha, deploymentDoc }) {
  const expectedSha = text(env.HARD_LAUNCH_EXPECTED_SHA);
  if (!/^[0-9a-f]{40}$/.test(expectedSha)) {
    throw new Error('HARD_LAUNCH_EXPECTED_SHA must be a lowercase 40-character SHA.');
  }
  if (currentCommitSha !== expectedSha || text(env.GITHUB_SHA) !== expectedSha) {
    throw new Error('Fresh hard-clearance state must execute from the exact release commit.');
  }
  if (text(env.GITHUB_ACTIONS) !== 'true') {
    throw new Error('Fresh hard-clearance state may only be generated by GitHub Actions.');
  }
  if (text(env.GITHUB_EVENT_NAME) !== 'workflow_dispatch') {
    throw new Error('Fresh hard-clearance state requires a protected workflow dispatch.');
  }
  if (text(env.GITHUB_WORKFLOW) !== EXPECTED_WORKFLOW) {
    throw new Error(`Fresh hard-clearance state requires the ${EXPECTED_WORKFLOW} workflow.`);
  }
  if (text(env.GITHUB_JOB) !== EXPECTED_JOB) {
    throw new Error(`Fresh hard-clearance state requires the ${EXPECTED_JOB} job.`);
  }
  if (text(env.GITHUB_REF) !== 'refs/heads/main') {
    throw new Error('Fresh hard-clearance state may only be generated from refs/heads/main.');
  }
  if (text(env.DEPLOYMENT_ENVIRONMENT) !== 'production') {
    throw new Error('Fresh hard-clearance state requires the protected production environment.');
  }
  if (text(deploymentDoc?.projectId) !== EXPECTED_PROJECT_ID) {
    throw new Error(`Source deployment must target ${EXPECTED_PROJECT_ID}.`);
  }
  if (text(deploymentDoc?.deployedCommitSha) !== expectedSha) {
    throw new Error('Source deployment SHA does not match the hard-clearance release SHA.');
  }
}

function runDeploymentVerifier({ root, env }) {
  const childEnv = { ...env };
  delete childEnv.HARD_CLEARANCE_PRODUCTION_STATE_PATH;
  const result = spawnSync(
    process.execPath,
    [path.join(root, 'scripts/verify-production-deployment.mjs'), '--write-evidence'],
    {
      cwd: root,
      env: childEnv,
      encoding: 'utf8',
      stdio: ['ignore', 'inherit', 'inherit'],
    },
  );
  if ((result.status ?? 1) !== 0) {
    throw new Error('Fresh hosted-client/deployment verification failed.');
  }
}

export async function generateHardClearanceProductionState({
  root = process.cwd(),
  env = process.env,
  now = new Date(),
  currentCommitSha = gitSha(root),
  deploymentPath = deploymentEvidencePath(root),
  statePath = path.join(root, HARD_CLEARANCE_PRODUCTION_STATE_RELATIVE_PATH),
  verifyPhoneAuth = verifyFirebasePhoneAuthProduction,
  verifyAdminMfa = verifyAdminMfaProduction,
  verifyMailboxes = runProductionOtpMailboxPreflight,
  verifyDeployment = runDeploymentVerifier,
} = {}) {
  const originalDeploymentRaw = readFileSync(deploymentPath, 'utf8');
  const deploymentDoc = parseJson(originalDeploymentRaw, 'production-deployment.json');
  assertProtectedContext({ env, currentCommitSha, deploymentDoc });

  const evidenceEnv = {
    ...env,
    GITHUB_SHA: text(deploymentDoc.deployedCommitSha),
    GITHUB_REPOSITORY: text(deploymentDoc.repository),
    GITHUB_REF: text(deploymentDoc.workflowRef),
    GITHUB_RUN_ID: text(deploymentDoc.workflowRunId),
    GITHUB_RUN_ATTEMPT: String(deploymentDoc.workflowRunAttempt || ''),
  };

  const [firebasePhoneAuth, adminMfa, mailboxResult] = await Promise.all([
    verifyPhoneAuth({ env: evidenceEnv, now }),
    verifyAdminMfa({ env: evidenceEnv, now }),
    verifyMailboxes({ env }),
  ]);

  let refreshedDeploymentDoc;
  const stagedDeploymentDoc = {
    ...deploymentDoc,
    firebasePhoneAuth,
    adminMfa,
  };
  writeFileSync(deploymentPath, `${JSON.stringify(stagedDeploymentDoc, null, 2)}\n`);
  try {
    verifyDeployment({ root, env });
    refreshedDeploymentDoc = parseJson(
      readFileSync(deploymentPath, 'utf8'),
      'freshly verified production-deployment.json',
    );
  } finally {
    // The original deployment artifact is immutable provenance. The temporary
    // working copy is restored byte-for-byte even when live verification fails.
    writeFileSync(deploymentPath, originalDeploymentRaw);
  }

  const originalDeploymentDigest = sha256Text(originalDeploymentRaw);
  const state = buildHardClearanceProductionState({
    deploymentDoc,
    originalDeploymentDigest,
    firebasePhoneAuth,
    adminMfa,
    hostedClientConfig: refreshedDeploymentDoc?.clientRuntimeConfig,
    mailboxResult,
    env,
    now,
  });
  const failures = validateHardClearanceProductionState(state, {
    expectedReleaseSha: text(env.HARD_LAUNCH_EXPECTED_SHA),
    repository: text(env.GITHUB_REPOSITORY),
    ref: text(env.GITHUB_REF),
    workflowName: text(env.GITHUB_WORKFLOW),
    workflowRunId: text(env.GITHUB_RUN_ID),
    workflowRunAttempt: Number(env.GITHUB_RUN_ATTEMPT || 0) || null,
    deploymentDoc,
    originalDeploymentDigest,
    now: now.getTime(),
  });
  if (failures.length > 0) {
    throw new Error(`Fresh hard-clearance production state is invalid: ${failures.join('; ')}`);
  }

  mkdirSync(path.dirname(statePath), { recursive: true });
  writeFileSync(statePath, `${JSON.stringify(state, null, 2)}\n`);
  console.log(
    '[hard-clearance-state] PASS — Phone Auth, Founder MFA, hosted Firebase/App Check, '
      + 'and protected mailbox access were freshly verified; secret_values_logged=false',
  );
  return state;
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : '';
if (invokedPath && invokedPath === fileURLToPath(import.meta.url)) {
  generateHardClearanceProductionState().catch((error) => {
    const message = error instanceof Error ? error.message : 'Fresh production-state generation failed.';
    console.error(`[hard-clearance-state] FAIL ${message}`);
    process.exit(1);
  });
}

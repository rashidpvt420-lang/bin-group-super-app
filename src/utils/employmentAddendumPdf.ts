export function buildEmploymentAddendumDoc(input: EmploymentAddendumInput) {
  const ncError = validateNonCompete(resolveNonCompete(input));
  if (ncError) throw new Error(ncError);

  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  registerArabicFont(doc);
  const issueDate = input.issueDate || new Date();
  doc.setProperties({ title: `Employment Addendum - ${input.employeeName}`, subject: 'Company Employment Addendum (supplements MOHRE contract)', author: COMPANY_DISPLAY_NAME, creator: 'BIN-GROUPS Super App' });

  const bottom = 280;
  let y = 16;
  const ensure = (needed: number) => {
    if (y + needed > bottom) { doc.addPage(); y = 16; }
  };

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  writeLTR(doc, COMPANY_DISPLAY_NAME, 105, y, { align: 'center' });
  y += 7;
  doc.setFontSize(12);
  writeLTR(doc, 'EMPLOYMENT CONTRACT ADDENDUM', 105, y, { align: 'center' });
  y += 7;
  writeRTL(doc, 'ملحق عقد العمل', 195, y);
  y += 5;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  y = wrappedLTR(doc, COMPANY_TRADING_AS_EN, 15, y, 180, 3.2);
  y = wrappedRTL(doc, COMPANY_TRADING_AS_AR, 195, y + 1, 180, 3.6);
  y = wrappedLTR(doc, COMPANY_REGISTRATION_LINE_EN, 15, y + 1, 180, 3.2) + 2;
  doc.setDrawColor(40);
  doc.line(15, y, 195, y);
  y += 6;

  doc.setFontSize(9);
  const parties = [
    `Reference: ${input.referenceNumber}    Date: ${fmt(issueDate)}`,
    `Employee: ${input.employeeName}    ID / Passport ref.: ${input.employeeIdRef || '[ID REF]'}`,
    `Job title: ${input.jobTitle}    MOHRE contract no.: ${input.mohreContractNo || '[MOHRE CONTRACT NO.]'}    Start date: ${fmt(input.startDate)}`,
  ];
  for (const line of parties) { writeLTR(doc, line, 15, y); y += 5; }
  y += 3;

  for (const clause of buildEmploymentAddendumClauses(input)) {
    doc.setFontSize(9);
    const enLines = doc.splitTextToSize(clause.en, 180).length;
    ensure(10 + enLines * 4.2);
    doc.setFont('helvetica', 'bold');
    writeLTR(doc, clause.titleEn, 15, y);
    writeRTL(doc, clause.titleAr, 195, y + 5);
    y += 10;
    doc.setFont('helvetica', 'normal');
    y = wrappedLTR(doc, clause.en, 15, y, 180, 4.2) + 1;
    const arLines = doc.splitTextToSize(clause.ar, 180).length;
    ensure(arLines * 5);
    y = wrappedRTL(doc, clause.ar, 195, y + 2, 180, 5) + 4;
  }

  ensure(40);
  y += 4;
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  writeLTR(doc, `For the Employer: ${COMPANY_IDENTITY.authorisedSignatoryEn} (${COMPANY_IDENTITY.authorisedSignatoryTitleEn})`, 15, y);
  writeRTL(doc, `عن صاحب العمل: ${COMPANY_IDENTITY.authorisedSignatoryAr} (${COMPANY_IDENTITY.authorisedSignatoryTitleAr})`, 195, y + 5);
  y += 16;
  doc.line(15, y, 85, y);
  doc.line(125, y, 195, y);
  y += 5;
  writeLTR(doc, 'Employer signature & company stamp', 15, y);
  writeLTR(doc, `Employee: ${input.employeeName}`, 125, y);
  y += 8;
  doc.setFontSize(7);
  wrappedLTR(doc, EMPLOYMENT_ADDENDUM_DISCLAIMER, 15, Math.min(y, 285), 180, 3.2);

  return { doc, filename: `Employment_Addendum_${input.referenceNumber}.pdf` };
}

export function generateEmploymentAddendumPdf(input: EmploymentAddendumInput) {
  const { doc, filename } = buildEmploymentAddendumDoc(input);
  return savePdfMobileSafe(doc, filename);
}

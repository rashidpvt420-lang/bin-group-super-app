export const NON_COMPETE_MAX_MONTHS = 24; // Art. 10(1): not more than two years from contract expiry.

export const NON_COMPETE_DEFAULT_PLACE = 'the United Arab Emirates';
export const NON_COMPETE_DEFAULT_PLACE_AR = 'دولة الإمارات العربية المتحدة';

export type NonCompeteTerms = {
  /** Required per employee; 1-24 months (Art. 10(1)). */
  months: number;
  place?: string;
  placeAr?: string;
  typeOfWork?: string;
  typeOfWorkAr?: string;
};

export type EmploymentAddendumInput = {
  employeeName: string;
  employeeIdRef?: string;
  jobTitle: string;
  mohreContractNo?: string;
  startDate?: Date;
  referenceNumber: string;
  issueDate?: Date;
  /**
   * Art. 10(1): a non-compete may only be imposed where the work gives the employee knowledge of the
   * employer's clients or access to its work secrets. Owner decision (14 Oct 2026): included by default
   * for roles with direct client access or confidential information; not for other roles.
   */
  roleAccess: { directClientAccess: boolean; confidentialInformation: boolean };
  /** Required (1-24 months) when roleAccess qualifies; area defaults to the UAE. */
  nonCompete?: NonCompeteTerms | null;
  /** Explicit opt-out for a qualifying role; set only on legal advice. */
  excludeNonCompete?: boolean;
};

export type AddendumClause = { titleEn: string; titleAr: string; en: string; ar: string };

export const EMPLOYMENT_ADDENDUM_DISCLAIMER =
  'Template generated by the BIN-GROUPS Super App. It supplements, and does not replace, the MOHRE employment contract. It must be reviewed by a UAE-licensed lawyer before use.';

const fmt = (d?: Date) => (d ? d.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' }) : '[DATE]');

export function roleQualifiesForNonCompete(roleAccess: EmploymentAddendumInput['roleAccess'] | undefined): boolean {
  return Boolean(roleAccess?.directClientAccess || roleAccess?.confidentialInformation);
}

export function resolveNonCompete(input: Pick<EmploymentAddendumInput, 'nonCompete' | 'excludeNonCompete' | 'jobTitle' | 'roleAccess'>): Required<NonCompeteTerms> | null {
  if (!roleQualifiesForNonCompete(input.roleAccess)) {
    if (input.nonCompete) throw new Error('A non-compete may only be added for roles with direct client access or confidential information (Federal Decree-Law No. 33 of 2021, Art. 10(1)).');
    return null;
  }
  if (input.excludeNonCompete) return null;
  const t = input.nonCompete;
  if (!t) throw new Error('Non-compete duration (months) is required for roles with direct client access or confidential information unless excludeNonCompete is set.');
  return {
    months: t.months,
    place: t.place?.trim() || NON_COMPETE_DEFAULT_PLACE,
    placeAr: t.placeAr?.trim() || NON_COMPETE_DEFAULT_PLACE_AR,
    typeOfWork: t.typeOfWork?.trim() || `the type of work the Employee performed for the Employer as ${input.jobTitle}`,
    typeOfWorkAr: t.typeOfWorkAr?.trim() || `نوع العمل الذي كان يؤديه العامل لدى صاحب العمل بوظيفة ${input.jobTitle}`,
  };
}

export function validateNonCompete(terms?: NonCompeteTerms | null): string | null {
  if (!terms) return null;
  if (!Number.isInteger(terms.months) || terms.months <= 0) return 'Non-compete duration must be a whole, positive number of months.';
  if (terms.months > NON_COMPETE_MAX_MONTHS) return `Non-compete may not exceed ${NON_COMPETE_MAX_MONTHS} months (Federal Decree-Law No. 33 of 2021, Art. 10(1)).`;
  if (!terms.place?.trim() || !terms.typeOfWork?.trim() || !terms.placeAr?.trim() || !terms.typeOfWorkAr?.trim()) {
    return 'Non-compete must state place and type of work in English and Arabic (Art. 10(1)).';
  }
  return null;
}

